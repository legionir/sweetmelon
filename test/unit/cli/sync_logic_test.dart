import 'package:flutter_test/flutter_test.dart';
import 'package:sweetmelon/cli/analysis_excludes.dart';
import 'package:sweetmelon/cli/native_sync.dart';
import 'package:sweetmelon/cli/plugin_closure.dart';
import 'package:sweetmelon/cli/pubspec_sync.dart';
import 'package:sweetmelon/cli/text_blocks.dart';

String _lines(List<String> lines) => lines.join('\n');

void main() {
  group('replaceMarkedBlock', () {
    const open = '// <sweetmelon:demo>';
    const close = '// </sweetmelon:demo>';

    test('rewrites only the lines between the markers', () {
      final text = _lines(['before', '  $open', '  old', '  $close', 'after']);
      final result = replaceMarkedBlock(
        text,
        name: 'demo',
        openTag: open,
        closeTag: close,
        indent: '  ',
        body: ['new 1', '', 'new 2'],
      );
      expect(
        result,
        _lines([
          'before',
          '  $open',
          '  new 1',
          '',
          '  new 2',
          '  $close',
          'after'
        ]),
      );
    });

    test('is idempotent', () {
      final text = _lines(['  $open', '  x', '  $close']);
      String run(String t) => replaceMarkedBlock(
            t,
            name: 'demo',
            openTag: open,
            closeTag: close,
            indent: '  ',
            body: ['x'],
          );
      expect(run(run(text)), run(text));
    });

    test('throws when the markers are missing', () {
      expect(
        () => replaceMarkedBlock('no markers',
            name: 'demo', openTag: open, closeTag: close, indent: '', body: []),
        throwsStateError,
      );
    });
  });

  group('generated analyzer excludes and test targets', () {
    const options = '''
analyzer:
  exclude:
    # <sweetmelon:disabled-plugin-sources>
    # old generated content
    # </sweetmelon:disabled-plugin-sources>
    - build/**
linter:
  rules: {}
''';

    test('keeps only marker-owned exclusions in sync', () {
      final result = syncAnalysisExcludes(
        options,
        disabledPluginDirs: {'nfc', 'camera_preview'},
        disabledTestPaths: {'test/plugins/nfc_plugin_test.dart'},
      );
      expect(result, contains('- lib/plugins/camera_preview/**'));
      expect(result, contains('- lib/plugins/nfc/**'));
      expect(result, contains('- test/plugins/nfc_plugin_test.dart'));
      expect(
        result,
        contains('# </sweetmelon:disabled-plugin-sources>\n    - build/**'),
      );
      expect(result, contains('linter:\n  rules: {}'));
      expect(
        syncAnalysisExcludes(
          result,
          disabledPluginDirs: {'nfc', 'camera_preview'},
          disabledTestPaths: {'test/plugins/nfc_plugin_test.dart'},
        ),
        result,
      );
    });

    test('only directive imports are reported as plugin imports', () {
      final source = [
        "import '",
        "package:sweetmelon/plugins/nfc/lib/nfc_plugin.dart';",
      ].join();
      expect(
        importedPluginDirectories('$source\n'
            "const catalog = 'package:sweetmelon/plugins/camera/lib/camera_plugin.dart';"),
        {'nfc'},
      );
    });

    test('plugin imports are found under a renamed Dart package', () {
      expect(
        importedPluginDirectories(
            "import 'package:my_app/plugins/nfc/lib/nfc_plugin.dart';\n"),
        {'nfc'},
      );
    });

    test('test target manifest is sorted and deduplicated', () {
      expect(
        renderActiveTestTargets(
            ['test/b_test.dart', 'test/a_test.dart', 'test/a_test.dart']),
        '''# Generated by sweetmelon sync; do not edit by hand.
# Tests that import a disabled plugin are intentionally omitted.
test/a_test.dart
test/b_test.dart
''',
      );
    });
  });

  group('removeUnusedDependencies', () {
    final pubspec = _lines([
      'name: sweetmelon',
      'dependencies:',
      '  flutter:',
      '    sdk: flutter',
      '',
      '  # Core',
      '  http: ^1.1.2',
      '  image_picker: ^1.0.4',
      '  local_thing:',
      '    path: ../local',
      '  nfc_manager: ^3.0.0',
      '',
      'dev_dependencies:',
      '  nfc_manager: ^3.0.0',
      '',
    ]);

    test('removes only packages that a disabled plugin needs alone', () {
      final result = removeUnusedDependencies(
        pubspec,
        disabledPluginDeps: {'image_picker', 'local_thing', 'nfc_manager'},
        neededPackages: {'http'},
      );
      expect(result.removed, ['image_picker', 'local_thing', 'nfc_manager']);
      expect(result.text, contains('  http: ^1.1.2'));
      expect(result.text, isNot(contains('image_picker')));
      expect(result.text, isNot(contains('local_thing')));
      expect(result.text, isNot(contains('path: ../local')));
      expect(result.text, contains('# Core'));
    });

    test('keeps a package that code outside disabled plugins still needs', () {
      final result = removeUnusedDependencies(
        pubspec,
        disabledPluginDeps: {'image_picker', 'nfc_manager'},
        neededPackages: {'image_picker'},
      );
      expect(result.removed, ['nfc_manager']);
      expect(result.text, contains('  image_picker: ^1.0.4'));
    });

    test('never edits dev_dependencies', () {
      final result = removeUnusedDependencies(
        pubspec,
        disabledPluginDeps: {'nfc_manager'},
        neededPackages: {},
      );
      expect(result.text.split('dev_dependencies:').last,
          contains('  nfc_manager: ^3.0.0'));
    });
  });

  group('PluginClosure', () {
    final pluginDeps = {
      'camera': {'image_picker'},
      'nfc': {'nfc_manager'},
      'geo': {'geolocator'},
    };

    test('a disabled plugin that nothing imports is not active', () {
      final closure = PluginClosure.compute(
        files: {'lib/app.dart': "import 'package:http/http.dart';"},
        pluginDeps: pluginDeps,
        enabled: {'camera': false, 'nfc': false, 'geo': false},
      );
      expect(closure.activeDirs, isEmpty);
      expect(closure.neededPackages, contains('http'));
      expect(closure.neededPackages, isNot(contains('image_picker')));
    });

    test('a disabled plugin still imported by lib/ stays active', () {
      final closure = PluginClosure.compute(
        files: {
          'lib/di/service_locator.dart':
              "import 'package:sweetmelon/plugins/camera/lib/camera_plugin.dart';",
        },
        pluginDeps: pluginDeps,
        enabled: {'camera': false, 'nfc': false, 'geo': false},
      );
      expect(closure.activeDirs, {'camera'});
      expect(closure.importedBy['camera'], 'lib/di/service_locator.dart');
      expect(closure.neededPackages, contains('image_picker'));
    });

    test('a plugin imported only by a disabled plugin stays inactive', () {
      final closure = PluginClosure.compute(
        files: {
          'lib/plugins/nfc/lib/nfc_plugin.dart':
              "import 'package:sweetmelon/plugins/geo/lib/geo.dart';",
        },
        pluginDeps: pluginDeps,
        enabled: {'camera': true, 'nfc': false, 'geo': false},
      );
      expect(closure.activeDirs, {'camera'});
    });

    test('a local path dependency of an enabled plugin stays active', () {
      final closure = PluginClosure.compute(
        files: const {},
        pluginDeps: {
          'safe_area': {'qr_scanner'},
          'qr_scanner': {'mobile_scanner'},
        },
        enabled: {'safe_area': true, 'qr_scanner': false},
      );
      expect(closure.activeDirs, {'safe_area', 'qr_scanner'});
      expect(closure.importedBy['qr_scanner'],
          'lib/plugins/safe_area/pubspec.yaml');
      expect(closure.neededPackages, contains('mobile_scanner'));
    });

    test('paths inside strings are not treated as plugin imports', () {
      final closure = PluginClosure.compute(
        files: {
          'lib/cli/catalog.dart':
              "const path = 'package:sweetmelon/plugins/nfc/lib/nfc_plugin.dart';",
        },
        pluginDeps: pluginDeps,
        enabled: {'camera': false, 'nfc': false, 'geo': false},
      );
      expect(closure.activeDirs, isEmpty);
    });

    test('dependencies of enabled plugins are needed', () {
      final closure = PluginClosure.compute(
        files: {},
        pluginDeps: pluginDeps,
        enabled: {'camera': true, 'nfc': false, 'geo': false},
      );
      expect(closure.neededPackages, {'image_picker'});
    });

    test('a plugin without a yaml entry counts as enabled', () {
      final closure = PluginClosure.compute(
        files: {},
        pluginDeps: pluginDeps,
        enabled: {'camera': false},
      );
      expect(closure.activeDirs, {'nfc', 'geo'});
    });
  });

  group('syncAndroidPermissions', () {
    final manifest = _lines([
      '<manifest xmlns:android="http://schemas.android.com/apk/res/android">',
      '    <uses-permission android:name="android.permission.INTERNET"/>',
      '    <uses-permission android:name="android.permission.CAMERA"/>',
      '    <uses-permission android:name="android.permission.READ_PHONE_STATE"/>',
      '    <application',
      '        android:label="x">',
      '    </application>',
      '</manifest>',
      '',
    ]);

    test('removes managed permissions that are not needed and keeps others',
        () {
      final out = syncAndroidPermissions(
        manifest,
        managed: {'android.permission.CAMERA', 'android.permission.NFC'},
        desired: ['android.permission.NFC'],
      );
      expect(out, isNot(contains('android.permission.CAMERA')));
      expect(out, contains('android.permission.INTERNET'));
      expect(out, contains('android.permission.READ_PHONE_STATE'));
      expect(
          out,
          contains(
              '    <uses-permission android:name="android.permission.NFC"/>'));
    });

    test('adds a needed permission inside the marker block, once', () {
      final out = syncAndroidPermissions(
        manifest,
        managed: {'android.permission.NFC'},
        desired: ['android.permission.NFC'],
      );
      expect(out, contains(androidPermissionsOpen));
      expect(out.indexOf(androidPermissionsOpen),
          lessThan(out.indexOf('    <application')));
      expect(
        'android.permission.NFC'.allMatches(out).length,
        1,
      );
    });

    test('a second run gives the same text', () {
      String run(String m) => syncAndroidPermissions(
            m,
            managed: {'android.permission.CAMERA', 'android.permission.NFC'},
            desired: ['android.permission.CAMERA', 'android.permission.NFC'],
          );
      final once = run(manifest);
      expect(run(once), once);
    });

    test('removes the block when nothing is needed', () {
      final withBlock = syncAndroidPermissions(
        manifest,
        managed: {'android.permission.NFC'},
        desired: ['android.permission.NFC'],
      );
      final out = syncAndroidPermissions(
        withBlock,
        managed: {'android.permission.NFC'},
        desired: [],
      );
      expect(out, isNot(contains(androidPermissionsOpen)));
      expect(out, isNot(contains('android.permission.NFC')));
    });
  });

  group('syncAndroidFeatures', () {
    const manifest = '''
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <uses-feature android:name="android.hardware.nfc" android:required="false"/>
    <uses-feature android:name="android.hardware.camera" android:required="false"/>
    <application android:label="x"/>
</manifest>
''';

    test('removes disabled managed features and keeps unmanaged features', () {
      final out = syncAndroidFeatures(
        manifest,
        managed: {'android.hardware.nfc'},
        desired: const [],
      );
      expect(out, isNot(contains('android.hardware.nfc')));
      expect(out, contains('android.hardware.camera'));
    });

    test('adds features inside a marker block and is idempotent', () {
      String run(String text) => syncAndroidFeatures(
            text,
            managed: {'android.hardware.nfc'},
            desired: ['android.hardware.nfc'],
          );
      final withoutNfc = manifest.replaceFirst(
        '    <uses-feature android:name="android.hardware.nfc" android:required="false"/>\n',
        '',
      );
      final once = run(withoutNfc);
      expect(once, contains(androidFeaturesOpen));
      expect(run(once), once);
    });
  });

  group('syncIosUsageDescriptions', () {
    final plist = _lines([
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<plist version="1.0">',
      '<dict>',
      '\t<key>CFBundleName</key>',
      '\t<string>x</string>',
      '\t<key>NSCameraUsageDescription</key>',
      '\t<string>My own text</string>',
      '\t<key>NSContactsUsageDescription</key>',
      '\t<string>old contacts text</string>',
      '</dict>',
      '</plist>',
      '',
    ]);

    test('keeps the text of a key that already exists', () {
      final out = syncIosUsageDescriptions(
        plist,
        managedKeys: {'NSCameraUsageDescription'},
        desired: {'NSCameraUsageDescription': 'from registry'},
      );
      expect(out, contains('\t<string>My own text</string>'));
      expect(out, isNot(contains('from registry')));
    });

    test('adds a missing key with the registry text, before </dict>', () {
      final out = syncIosUsageDescriptions(
        plist,
        managedKeys: {'NSMicrophoneUsageDescription'},
        desired: {'NSMicrophoneUsageDescription': 'Microphone & audio'},
      );
      expect(out, contains('\t<key>NSMicrophoneUsageDescription</key>'));
      expect(out, contains('Microphone &amp; audio'));
      expect(out.indexOf('NSMicrophoneUsageDescription'),
          lessThan(out.indexOf('</dict>')));
    });

    test('removes a managed key that is not needed, keeps unmanaged keys', () {
      final out = syncIosUsageDescriptions(
        plist,
        managedKeys: {'NSContactsUsageDescription'},
        desired: {},
      );
      expect(out, isNot(contains('NSContactsUsageDescription')));
      expect(out, contains('CFBundleName'));
    });

    test('a second run gives the same text', () {
      String run(String t) => syncIosUsageDescriptions(
            t,
            managedKeys: {'NSMicrophoneUsageDescription'},
            desired: {'NSMicrophoneUsageDescription': 'Mic'},
          );
      final once = run(plist);
      expect(run(once), once);
    });
  });
}
