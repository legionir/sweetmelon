/// Matches plugin imports only when they occur in a Dart import/export
/// directive. Catalog strings and comments are deliberately ignored.
final pluginImportDirective = RegExp(
  r'''^\s*(?:import|export)\s+['"]package:sweetmelon/plugins/([a-z0-9_]+)/''',
  multiLine: true,
);

/// Returns the plugin directories directly imported by [source].
Set<String> importedPluginDirectories(String source) => {
      for (final match in pluginImportDirective.allMatches(source))
        match.group(1)!,
    };

/// Rewrites the marker-owned analyzer exclusions for source code and tests
/// whose plugin is disabled in sweetmelon.yaml. Disabled sources remain in the
/// repository and are available again when their plugin is re-enabled.
String syncAnalysisExcludes(
  String source, {
  required Iterable<String> disabledPluginDirs,
  required Iterable<String> disabledTestPaths,
}) {
  final dirs = disabledPluginDirs.toSet().toList()..sort();
  final tests = disabledTestPaths.toSet().toList()..sort();
  return replaceMarkedBlock(
    source,
    name: 'disabled-plugin-sources',
    openTag: '# <sweetmelon:disabled-plugin-sources>',
    closeTag: '# </sweetmelon:disabled-plugin-sources>',
    indent: '    ',
    body: [
      '# Plugin source is retained but not part of this configured build.',
      for (final dir in dirs) '- lib/plugins/$dir/**',
      if (tests.isNotEmpty) '',
      if (tests.isNotEmpty)
        '# Tests for disabled plugins are selected out by the generated test manifest.',
      for (final path in tests) '- $path',
    ],
  );
}

/// Builds the explicit test target list used by CI. Passing individual files
/// prevents `flutter test test/` from compiling tests for disabled plugins
/// whose optional third-party package has been removed from pubspec.yaml.
String renderActiveTestTargets(Iterable<String> paths) {
  final sorted = paths.toSet().toList()..sort();
  return [
    '# Generated by sweetmelon sync; do not edit by hand.',
    '# Tests that import a disabled plugin are intentionally omitted.',
    ...sorted,
    '',
  ].join('\n');
}
